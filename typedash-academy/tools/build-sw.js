#!/usr/bin/env node
/*
 * Regenerates sw.js with the current list of app files and a content-hash cache version.
 * Run after adding/changing files:  node tools/build-sw.js
 * (Only needed when the app is served over http(s); opening index.html from disk never uses it.)
 */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const INCLUDE = ['index.html', 'manifest.webmanifest', 'assets', 'css', 'js'];
const files = [];
function walk(rel) {
  const abs = path.join(ROOT, rel);
  const st = fs.statSync(abs);
  if (st.isDirectory()) fs.readdirSync(abs).sort().forEach((f) => { if (!f.startsWith('.')) walk(path.join(rel, f)); });
  else files.push(rel.split(path.sep).join('/'));
}
INCLUDE.forEach(walk);
const hash = crypto.createHash('sha1');
files.forEach((f) => hash.update(f).update(fs.readFileSync(path.join(ROOT, f))));
const version = hash.digest('hex').slice(0, 10);

const sw = `/* TypeDash Academy service worker (generated by tools/build-sw.js — do not edit by hand). */
'use strict';
const CACHE = 'tda-${version}';
const ASSETS = ${JSON.stringify(['./', ...files], null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('tda-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); }
    return res;
  }).catch(() => caches.match('./index.html'))));
});
`;
fs.writeFileSync(path.join(ROOT, 'sw.js'), sw);
console.log(`sw.js written: ${files.length} files, cache tda-${version}`);
